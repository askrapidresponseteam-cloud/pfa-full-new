#!/usr/bin/env node
/* Ready-made CSR projects, each at a fixed price, on csr.html and as a
   one-page PDF a company can take into its CSR committee (owner, 3 Nov
   2026: "Make 6 to 8 ready-made projects with a fixed price, each as a
   one-page PDF. Examples: an ambulance with a year of running costs, a
   sterilisation drive for one town, training village vet assistants").

     node scripts/build-csr-projects.js            the section in csr.html and media/csr/*.pdf
     node scripts/build-csr-projects.js --check    fails if csr.html is out of date

   The projects, their prices and what each rupee pays for are in
   data/csr-projects.json; change them there and run this again. */

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'data', 'csr-projects.json');
const OUT = path.join(ROOT, 'media', 'csr');
const OPEN = '<!-- csr-projects:start  generated by scripts/build-csr-projects.js - do not edit by hand -->';
const CLOSE = '<!-- csr-projects:end -->';

function esc(v) { return String(v == null ? '' : v).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c])); }
function projects() { return JSON.parse(fs.readFileSync(DATA, 'utf8')).projects; }

/* 3175000 -> "₹31.75 lakh" */
function lakh(n) {
  const l = n / 1e5;
  return '₹' + (Number.isInteger(l) ? String(l) : l.toFixed(2).replace(/0$/, '')) + ' lakh';
}
function rupees(n) { return '₹' + Number(n).toLocaleString('en-IN'); }
function plain(s) { return String(s || '').replace(/\bRs\.? ?/g, '₹'); }

/* who a project suits, as a few short words */
function tags(p) {
  const all = p.suits.join(' ').toLowerCase();
  const out = [];
  [['pet', 'Pet care'], ['pharma', 'Pharma'], ['dairy', 'Dairy'], ['agri', 'Agriculture'], ['medical device', 'Medical devices'], ['real estate', 'Construction'], ['mid-size', 'Mid-size companies']]
    .forEach(([k, label]) => { if (all.includes(k) && !out.includes(label)) out.push(label); });
  return out;
}

function section(list) {
  const items = list.map((p) => `
        <details id="project-${esc(p.id)}"><summary><span class="cp__name">${esc(p.name)}</span><span class="cp__price">${esc(lakh(p.price))}</span></summary>
          <div class="cp__body">
          <p>${esc(p.pitch)}</p>
          <p><b>Suits:</b> ${esc(tags(p).join(', '))}.</p>
          <p><b>Delivered:</b> ${esc(p.what)}. ${esc(p.scale)}. ${esc(p.time)}, in ${esc(p.where.charAt(0).toLowerCase() + p.where.slice(1))}.</p>
          <table class="cp__lines"><tbody>${p.lines.map((l) => `<tr><td>${esc(plain(l.item))}</td><td>${esc(rupees(l.inr))}</td></tr>`).join('')}<tr class="cp__sum"><td>Fixed price</td><td>${esc(rupees(p.price))}</td></tr></tbody></table>
          <p><b>You can report:</b> ${esc(p.outcomes.join('; '))}.</p>
          ${p.smaller ? `<p><b>Smaller budget:</b> ${esc(plain(p.smaller))}.</p>` : ''}
          <p class="cp__law">Companies Act, Schedule VII: ${esc(p.schedule)}.${p.note ? ' ' + esc(p.note) : ''}</p>
          <div class="cp__acts"><a class="btn" href="#start" data-csr-pick="${esc(p.name)}" data-csr-price="${p.price}">Fund this</a><a class="cp__pdf" href="media/csr/${esc(p.id)}.pdf" download>One-page PDF</a></div>
          </div>
        </details>`).join('');
  /* styled by assets/micro.css (#projects) */
  return `${OPEN}
  <section class="band m-twin" id="projects">
    <div class="band__head">
      <p class="eyebrow">Ready to fund</p>
      <h2 class="display">${list.length} projects, fixed prices.</h2>
    </div>
    <div class="m-acc">${items}
    </div>
    <script>
    /* "Fund this" starts the brief with the project named in it and the budget band chosen */
    document.addEventListener('click', function (e) {
      var a = e.target.closest && e.target.closest('[data-csr-pick]');
      if (!a) return;
      var name = a.getAttribute('data-csr-pick'); var price = Number(a.getAttribute('data-csr-price')) || 0;
      var note = document.getElementById('message');
      var line = 'We would like to fund: ' + name + ' (Rs ' + price.toLocaleString('en-IN') + ').';
      if (note && note.value.indexOf(line) === -1) note.value = line + (note.value ? '\\n' + note.value : '');
      var band = price < 1e6 ? 'b1' : price <= 5e6 ? 'b2' : price <= 1e7 ? 'b3' : 'b4';
      var r = document.getElementById(band); if (r) r.checked = true;
      var span = document.getElementById('s1'); if (span) span.checked = true;
    });
    </script>
  </section>
  ${CLOSE}`;
}

function withSection(html, list) {
  const block = section(list);
  const a = html.indexOf(OPEN);
  if (a > -1) { const b = html.indexOf(CLOSE, a) + CLOSE.length; return html.slice(0, a) + block + html.slice(b); }
  const at = html.indexOf('  <section class="band m-twin" id="start"');
  if (at < 0) throw new Error('build-csr-projects: csr.html has no brief to sit before');
  return html.slice(0, at) + '  ' + block + '\n' + html.slice(at);
}

/* ---- the one-page PDF ------------------------------------------------------ */

function pdf(p) {
  const PDFDocument = require('pdfkit');
  const R = require('../lib/receipt-assets');
  return new Promise((resolve) => {
    const doc = new PDFDocument({ size: 'A4', margin: 0, info: { Title: `${p.name}: a CSR project with People for Animals`, Author: 'People for Animals', CreationDate: new Date('2026-11-03T00:00:00Z') } });
    const bufs = [];
    doc.on('data', (b) => bufs.push(b));
    doc.on('end', () => resolve(Buffer.concat(bufs)));
    doc.registerFont('display', Buffer.from(R.display.ttf, 'base64'));
    const W = 595.28; const M = 44; const col = W - 2 * M;
    const INK = '#111111'; const MUTED = '#5f5f5f'; const LINE = '#e4e2df';
    doc.image(Buffer.from(R.logo.jpeg, 'base64'), M, 34, { width: 96 });
    doc.font('Helvetica-Bold').fontSize(7.5).fillColor(MUTED).text('CSR PROJECT  ·  COMPANIES ACT, SCHEDULE VII ITEM (iv)', M, 46, { width: col, align: 'right', characterSpacing: 1 });
    let y = 92;
    doc.font('display').fontSize(22).fillColor(INK).text(p.name.toUpperCase(), M, y, { width: col * 0.66, lineGap: 3 });
    const titleEnd = doc.y;
    const priceY = y;
    doc.font('display').fontSize(26).text(lakh(p.price).replace('₹', 'Rs '), M + col * 0.68, priceY, { width: col * 0.32, align: 'right' });
    doc.font('Helvetica').fontSize(8).fillColor(MUTED).text('Fixed price, everything included', M + col * 0.68, priceY + 30, { width: col * 0.32, align: 'right' });
    y = Math.max(titleEnd, priceY + 44) + 12;
    doc.font('Helvetica').fontSize(10.5).fillColor(INK).text(p.pitch, M, y, { width: col, lineGap: 2 });
    y = doc.y + 14;
    doc.moveTo(M, y).lineTo(W - M, y).lineWidth(0.6).strokeColor(LINE).stroke();
    y += 12;
    const facts = [['What is delivered', p.what], ['How much', p.scale], ['How long', p.time], ['Where', p.where]];
    const fw = (col - 18) / 2;
    facts.forEach((f, i) => {
      const x = M + (i % 2) * (fw + 18);
      const yy = y + Math.floor(i / 2) * 52;
      doc.font('Helvetica-Bold').fontSize(7).fillColor(MUTED).text(f[0].toUpperCase(), x, yy, { width: fw, characterSpacing: 0.8 });
      doc.font('Helvetica').fontSize(9).fillColor(INK).text(f[1], x, yy + 11, { width: fw, height: 38, ellipsis: true, lineGap: 1 });
    });
    y += 108;
    doc.font('Helvetica-Bold').fontSize(7).fillColor(MUTED).text('WHAT YOUR CSR PAYS FOR', M, y, { characterSpacing: 0.8 });
    y += 14;
    p.lines.forEach((l) => {
      doc.font('Helvetica').fontSize(8.6).fillColor(INK);
      const h = doc.heightOfString(plain(l.item).replace(/₹/g, 'Rs '), { width: col - 90 });
      doc.text(plain(l.item).replace(/₹/g, 'Rs '), M, y, { width: col - 90 });
      doc.text('Rs ' + Number(l.inr).toLocaleString('en-IN'), M + col - 85, y, { width: 85, align: 'right' });
      y += h + 5;
      doc.moveTo(M, y - 2.5).lineTo(W - M, y - 2.5).lineWidth(0.4).strokeColor(LINE).stroke();
    });
    doc.font('Helvetica-Bold').fontSize(9).fillColor(INK).text('Fixed price', M, y + 2).text('Rs ' + Number(p.price).toLocaleString('en-IN'), M + col - 120, y + 2, { width: 120, align: 'right' });
    y += 24;
    doc.font('Helvetica-Bold').fontSize(7).fillColor(MUTED).text('WHAT YOU CAN REPORT', M, y, { characterSpacing: 0.8 });
    y += 13;
    p.outcomes.forEach((o) => { doc.font('Helvetica').fontSize(8.8).fillColor(INK).text('•  ' + o, M, y, { width: col }); y = doc.y + 3; });
    y += 8;
    const tail = [];
    if (p.smaller) tail.push(['Smaller budget', plain(p.smaller).replace(/₹/g, 'Rs ')]);
    tail.push(['Suits', tags(p).join(', ')]);
    tail.push(['Schedule VII', p.schedule + (p.note ? '. ' + p.note : '')]);
    tail.forEach(([k, v]) => {
      doc.font('Helvetica-Bold').fontSize(8.4).fillColor(INK).text(k + ': ', M, y, { continued: true }).font('Helvetica').fillColor(INK).text(v, { width: col });
      y = doc.y + 4;
    });
    const fy = 842 - 74;
    doc.moveTo(M, fy).lineTo(W - M, fy).lineWidth(0.6).strokeColor(LINE).stroke();
    doc.font('Helvetica-Bold').fontSize(8.5).fillColor(INK).text('People for Animals', M, fy + 10);
    doc.font('Helvetica').fontSize(7.8).fillColor(MUTED)
      .text('4-T, DCM Building, 16 Barakhamba Road, New Delhi 110001  ·  +91 11 2081 8191', M, fy + 23, { width: col })
      .text('Start at peopleforanimalsindia.org/csr. Registration (CSR-1, 12A, 80G) and audited accounts on request. Price holds for agreements signed by 31 March 2027; reports every quarter and at the close.', M, fy + 35, { width: col, lineGap: 1 });
    doc.end();
  });
}

async function run(check) {
  const list = projects();
  const file = path.join(ROOT, 'csr.html');
  const cur = fs.readFileSync(file, 'utf8');
  const next = withSection(cur, list);
  if (check) {
    const missing = list.filter((p) => !fs.existsSync(path.join(OUT, p.id + '.pdf'))).map((p) => p.id);
    if (next !== cur || missing.length) { console.error('CSR projects out of date, run: node scripts/build-csr-projects.js' + (missing.length ? ` (no PDF for ${missing.join(', ')})` : '')); process.exit(1); }
    console.log(`csr.html carries all ${list.length} projects, each with its PDF.`);
    return;
  }
  if (next !== cur) fs.writeFileSync(file, next);
  fs.mkdirSync(OUT, { recursive: true });
  for (const p of list) fs.writeFileSync(path.join(OUT, p.id + '.pdf'), await pdf(p));
  console.log(`${list.length} projects in csr.html and ${list.length} PDFs in media/csr/.`);
}

module.exports = { projects, lakh, tags, section };
if (require.main === module) run(process.argv.includes('--check'));
