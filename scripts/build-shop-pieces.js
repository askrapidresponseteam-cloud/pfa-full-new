#!/usr/bin/env node
/* The shop's pieces, for the Seasonal gifts page (lib/gift-seasons.js).

     node scripts/build-shop-pieces.js           writes lib/shop-pieces.json
     node scripts/build-shop-pieces.js --check   fails if it is out of date

   A gift collection names shop pieces by their id. Their name and price come
   from lib/shop.js, the one place a price is trusted; their photograph and
   their place on shop.html (the anchor a gift card links to) come from the
   shop page itself. Written to lib/ so it ships with the API. */

'use strict';

const fs = require('node:fs');
const path = require('node:path');
const SHOP = require('../lib/shop');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'lib', 'shop-pieces.json');

function build() {
  const html = fs.readFileSync(path.join(ROOT, 'shop.html'), 'utf8');
  const pieces = [];
  const re = /<article class="item" id="([^"]+)" data-id="([^"]+)"[^>]*?data-images="([^"]*)"/g;
  let m;
  while ((m = re.exec(html))) {
    const [, anchor, id, images] = m;
    const p = SHOP.get(id);
    if (!p) continue;
    pieces.push({
      id,
      anchor,
      name: p.name,
      designer: p.designer,
      price: p.price,
      listPrice: p.listPrice,
      available: p.available !== false,
      image: images.split('|').filter(Boolean)[0] || ''
    });
  }
  return JSON.stringify({ note: 'Generated by scripts/build-shop-pieces.js from shop.html and lib/shop.js. Do not edit.', pieces }, null, 1) + '\n';
}

if (require.main === module) {
  const next = build();
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (now !== next) { console.error('lib/shop-pieces.json is out of date: run node scripts/build-shop-pieces.js'); process.exit(1); }
    console.log('lib/shop-pieces.json is up to date');
  } else {
    fs.writeFileSync(OUT, next);
    console.log(`lib/shop-pieces.json: ${JSON.parse(next).pieces.length} pieces`);
  }
}

module.exports = { build };
