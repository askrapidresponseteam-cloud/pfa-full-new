'use strict';

/* The PFA units the site's assistant offers for "help near me"
   (assets/assistant.js), written to assets/assistant-units.js from the same
   list the unit pages are built from (scripts/build-unit-pages.js, which
   reads units.html), so the two can never differ.

     node scripts/build-assistant-units.js           writes it
     node scripts/build-assistant-units.js --check   fails if it is out of date */

const fs = require('fs');
const path = require('path');
const { build } = require('./build-unit-pages.js');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'assets', 'assistant-units.js');

function render() {
  /* with its address and email, so "address of pfa ahmedabad" is answered (22 Nov 2026) */
  const list = build().list.map((u) => Object.assign({ c: u.city, s: u.state, p: u.head, t: (u.phones || []).slice(0, 2), u: `units/${u.slug}.html`, la: u.la, lo: u.lo },
    u.address ? { a: u.address.replace(/\s*\.?\s*Ph(one)?\s*:.*$/i, '').trim() } : {}, u.email ? { e: u.email } : {}));
  return '/* PFA units for the assistant: generated by scripts/build-assistant-units.js from units.html. Do not edit by hand. */\n'
    + 'window.PFA_ASSIST_UNITS = ' + JSON.stringify(list) + ';\n';
}

if (require.main === module) {
  const text = render();
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (now !== text) { console.error('assets/assistant-units.js is out of date: run node scripts/build-assistant-units.js'); process.exit(1); }
    console.log('assistant units in step with units.html');
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`assets/assistant-units.js written: ${build().list.length} units`);
  }
}

module.exports = { render, OUT };
